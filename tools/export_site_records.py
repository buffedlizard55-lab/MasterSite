#!/usr/bin/env python3
"""Export one machine-readable record per public repository to data/sites/.

The multi-session protocol asks for per-site files named
`data/sites/<owner>__<repo>.json` so that parallel sessions work on separate
files instead of a shared master list. This repository's canonical records live
in `tools/overlay.json` (curated prose) and `data/sites.js` (generated API
telemetry); this script derives the per-site files from those two sources so the
three can never disagree.

Nothing here is hand-edited. Run it after `tools/build_data.py`:

    python3 tools/build_data.py && python3 tools/export_site_records.py

Use `--check` to verify the committed data/sites/ directory matches the current
snapshot without writing anything (this is what scripts/validate does).

Field notes (no invented values):
  * `verified` is a mechanical flag: true only when the entry carries a
    `lastVerified` stamp *and* a `verifiedAtSha` whose commit still matches the
    snapshot head. It means "the curated prose was read against a stated commit
    and that commit is still the head", not "every sentence is proven true".
  * `unverifiedFields` lists, by name, every field this export could not fill
    from an official source; scripts/validate requires that each name appears in
    FLAGGED.md. `null` is always preferred to a guess.
"""

import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data", "sites.js")
OVERLAY = os.path.join(ROOT, "tools", "overlay.json")
OUTDIR = os.path.join(ROOT, "data", "sites")
OWNER = "buffedlizard55-lab"
API = "https://api.github.com"


def load_snapshot():
    script = (
        "global.window={};require(%r);"
        "process.stdout.write(JSON.stringify(window.MASTERDATA));" % DATA
    )
    out = subprocess.run(["node", "-e", script], capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def license_note():
    return (
        "Generated by tools/export_site_records.py from tools/overlay.json and "
        "data/sites.js. Do not hand-edit: re-run the generators instead. Every "
        "factual claim below carries the official endpoint it came from."
    )


def build_records(d):
    """Return {filename: record} for every public repository in the snapshot."""
    records = {}
    for site in d["sites"]:
        repo = site["repo"]
        slug = "%s__%s" % (OWNER, repo)
        api_repo = "%s/repos/%s/%s" % (API, OWNER, repo)
        api_pages = api_repo + "/pages"
        api_commits = api_repo + "/commits?sha=%s" % (site.get("defaultBranch") or "main")
        api_repo_url = "%s/repos/%s/%s" % (API, OWNER, repo)
        sha = site.get("verifiedAtSha")
        head = site.get("headSha")
        stale = bool(site.get("proseStale"))
        verified = bool(site.get("lastVerified") and sha and not stale)

        nulls = [k for k in ("created", "lastCommit", "pushedAt", "updatedAt",
                             "pagesUrl", "pagesStatus", "sizeKb", "commits")
                 if site.get(k) is None]
        if not site.get("lastVerified"):
            nulls.append("lastVerified")
        if not sha:
            nulls.append("verifiedAtSha")
        if not site.get("verifiedBasis"):
            nulls.append("verifiedBasis")

        records[slug + ".json"] = {
            "owner": OWNER,
            "repo": repo,
            "title": site.get("title"),
            "category": site.get("category"),
            # Readability grouping derived mechanically from the official
            # repository name (tools/families.json). null = no family token
            # matched; this is a derived value, not an unverified one.
            "family": site.get("family"),
            "kind": site.get("kind"),
            "description": site.get("description"),
            "pagesUrl": site.get("pagesUrl"),
            "repoUrl": "https://github.com/%s/%s" % (OWNER, repo),
            "created": site.get("created"),
            "firstCommit": site.get("firstCommit"),
            "lastUpdated": site.get("lastCommit"),
            "lastUpdatedField": "lastCommit (newest committer timestamp on the default branch; "
                                "the public API exposes no site-visit or last-use date)",
            "pushedAt": site.get("pushedAt"),
            "updatedAt": site.get("updatedAt"),
            "commits": site.get("commits"),
            "defaultBranch": site.get("defaultBranch"),
            "pagesStatus": site.get("pagesStatus"),
            "pagesSource": site.get("pagesSource"),
            "sizeKb": site.get("sizeKb"),
            "flags": site.get("flags", []),
            "verified": verified,
            "verifiedAt": site.get("lastVerified"),
            "verifiedAtSha": sha,
            "snapshotHeadSha": head,
            "proseStale": stale,
            "verifiedBasis": site.get("verifiedBasis"),
            "sourceLinks": [u for u in (api_repo_url, api_pages, api_commits,
                                        site.get("pagesUrl")) if u],
            "snapshot": d.get("generated"),
            "unverifiedFields": sorted(set(nulls)),
            "licenseNote": license_note(),
        }
    return records


def main():
    check = "--check" in sys.argv[1:]
    d = load_snapshot()
    records = build_records(d)
    os.makedirs(OUTDIR, exist_ok=True)
    existing = sorted(f for f in os.listdir(OUTDIR) if f.endswith(".json"))
    problems = []

    if check:
        for name, record in sorted(records.items()):
            path = os.path.join(OUTDIR, name)
            if not os.path.exists(path):
                problems.append("missing %s" % name)
                continue
            on_disk = json.load(open(path, encoding="utf-8"))
            if on_disk != record:
                problems.append("stale %s" % name)
        for name in existing:
            if name not in records:
                problems.append("orphan %s (no longer in the snapshot)" % name)
        if problems:
            print("data/sites/ is out of sync with the snapshot (%d problem(s)):" % len(problems))
            for p in problems[:20]:
                print("  -", p)
            print("run: python3 tools/export_site_records.py")
            return 1
        print("data/sites/: %d per-site records in sync with snapshot %s"
              % (len(records), d.get("generated")))
        return 0

    for name, record in sorted(records.items()):
        with open(os.path.join(OUTDIR, name), "w", encoding="utf-8") as fh:
            json.dump(record, fh, indent=2, ensure_ascii=False)
            fh.write("\n")
    removed = [n for n in existing if n not in records]
    for name in removed:
        os.remove(os.path.join(OUTDIR, name))
    print("wrote %d per-site records to data/sites/ (snapshot %s)"
          % (len(records), d.get("generated")))
    if removed:
        print("removed %d orphaned record(s): %s" % (len(removed), ", ".join(removed)))
    unverified = sum(1 for r in records.values() if not r["verified"])
    print("  verified: %d   not machine-verified: %d (see FLAGGED.md)"
          % (len(records) - unverified, unverified))
    return 0


if __name__ == "__main__":
    sys.exit(main())
